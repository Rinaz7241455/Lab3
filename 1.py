# Лабораторная работа № 3. Вариант 8: «Делители»
# Поиск всех делителей натурального числа n и проверка на совершенное число

def main() -> None:
    # Цикл ввода с проверкой корректности (натуральное число n > 0)
    while True:
        n: int = int(input("Введите натуральное число n (> 0): "))
        if n > 0:
            break
        print("Число должно быть больше нуля. Повторите ввод.")

    divisors: list[int] = []
    proper_sum: int = 0

    # Перебор всех возможных делителей от 1 до n с помощью цикла for
    for i in range(1, n + 1):
        if n % i == 0:
            divisors.append(i)
            # Собственными считаются все делители, строго меньше самого числа n
            if i < n:
                proper_sum += i

    # Проверка условия совершенного числа (сумма собственных делителей равна n)
    is_perfect: bool = (proper_sum == n)
    verdict: str = "является совершенным" if is_perfect else "не является совершенным"

    # Вывод результатов в читаемом виде с пояснениями
    print("\n--- Результаты анализа делителей ---")
    print(f"Все делители числа {n}: {divisors}")
    print(f"Количество делителей: {len(divisors)}")
    print(f"Сумма собственных делителей: {proper_sum}")
    print(f"Вывод: число {n} {verdict}.")


if __name__ == "__main__":
    main()
